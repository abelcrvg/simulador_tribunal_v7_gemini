// Função para gerar documentos visuais em background (não bloqueia)
async function generateVisualDocumentsInBackground(trialId: number, trial: any) {
  console.log(`[Background] Iniciando geração de documentos visuais para trial ${trialId}`);
  
  const categories: Array<"cena_crime" | "planta_baixa" | "laudo_pericial" | "foto_prova"> = 
    ["cena_crime", "foto_prova", "laudo_pericial"];
  
  for (const category of categories) {
    try {
      let prompt = "";
      let title = "";

      switch (category) {
        case "cena_crime":
          title = "Foto da Cena do Crime";
          prompt = `Crie uma imagem realista da cena do crime para o caso: ${trial.title}. Fatos: ${trial.facts.substring(0, 500)}. Estilo: fotografia forense, evidências marcadas, iluminação profissional.`;
          break;
        case "foto_prova":
          title = "Fotografia de Prova Material";
          prompt = `Crie uma fotografia de prova material relacionada ao caso: ${trial.title}. Estilo: fotografia forense com régua de escala.`;
          break;
        case "laudo_pericial":
          title = "Laudo Pericial Ilustrado";
          prompt = `Crie uma ilustração técnica para laudo pericial do caso: ${trial.title}. Estilo: diagrama técnico, anotações, medições.`;
          break;
      }

      console.log(`[Background] Gerando imagem: ${category}`);
      const { url: imageUrl } = await generateImage({ prompt });
      
      if (imageUrl) {
        await db.createVisualDocument({
          trialId,
          type: "image",
          category,
          title,
          description: `Documento visual gerado automaticamente para ${trial.title}`,
          fileUrl: imageUrl,
          thumbnailUrl: imageUrl,
          metadata: JSON.stringify({ generatedAt: new Date(), prompt, autoGenerated: true }),
        });
        console.log(`[Background] Documento visual criado: ${title}`);
      }
    } catch (error: any) {
      console.error(`[Background] Erro ao gerar ${category}:`, error.message);
    }
  }
  
  console.log(`[Background] Geração de documentos visuais concluída para trial ${trialId}`);
}

