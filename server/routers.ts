// ============================================================
// RESOLUÇÃO CENTRALIZADA DE PARTICIPANTE/ALVO
// ============================================================
// Resolve nomes como "Marcos", "Sr. Marcos", "Dra. Maria"
// e retorna o papel do participante correspondente.
//
// O resolvedor recebe participants explicitamente para funcionar
// tanto em message.send quanto em continuar.
function resolveParticipantRole(
  text: string,
  participants: any[],
  excludeRole?: string
): string | null {
  const normalized = text
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[.,!?;:()[\]"']/g, " ");

  const candidates = participants
    .filter((p: any) => !excludeRole || p.role !== excludeRole)
    .filter((p: any) => p.name);

  // 1. Prioridade máxima: nome completo.
  // Isso evita que uma simples menção a "Marcos" seja confundida
  // com outro participante.
  for (const participant of candidates) {
    const participantName = participant.name
      .toLowerCase()
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .trim();

    if (
      participantName.length > 3 &&
      normalized.includes(participantName)
    ) {
      return participant.role;
    }
  }

  // 2. Procurar tratamento + primeiro nome.
  // Exemplos:
  // "Sr. Marcos"
  // "Dra. Maria"
  // "Dr. João"
  const directAddressPattern =
    /(?:sr|sra|srta|dr|dra|doutor|doutora|senhor|senhora)\s+([a-zÀ-ÿ]{3,})/gi;

  const directNames: string[] = [];
  let match: RegExpExecArray | null;

  while ((match = directAddressPattern.exec(text)) !== null) {
    directNames.push(
      match[1]
        .toLowerCase()
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
    );
  }

  for (const name of directNames) {
    const participant = candidates.find((p: any) => {
      const parts = p.name
        .toLowerCase()
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
        .split(/\s+/);

      return parts.includes(name);
    });

    if (participant) {
      return participant.role;
    }
  }

  // 3. Nome isolado em posição de chamada.
  // Exemplos:
  // "Marcos, responda."
  // "Marcos: o senhor..."
  // "Marcos responda."
  for (const participant of candidates) {
    const parts = participant.name
      .toLowerCase()
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .split(/\s+/)
      .filter((part: string) => part.length >= 4);

    for (const part of parts) {
      const directNamePattern = new RegExp(
        `(?:^|[\\s,.:;!?])${part}(?:[\\s,.:;!?]|$)`,
        "i"
      );

      if (directNamePattern.test(normalized)) {
        return participant.role;
      }
    }
  }

  return null;
}

