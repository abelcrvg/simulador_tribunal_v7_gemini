// fatores devem influenciar sua reação.
//
// A personalidade é persistente durante toda a sessão.
// O comportamento NÃO deve ser sorteado a cada fala.

function normalizeParticipantText(value: unknown): string {
  return String(value ?? "").trim();
}

function buildParticipantBehaviorContext(
  participant: any,
  messageHistory: any[],
  trial: any,
  evidences: any[] = []
): string {
  const participantName =
    normalizeParticipantText(participant?.name) || "Participante";

  const role =
    normalizeParticipantText(participant?.role) || "participante";

  const description =
    normalizeParticipantText(participant?.description) ||
    "Nenhuma descrição adicional disponível.";

  const personality =
    normalizeParticipantText(participant?.personality) ||
    "Personalidade não especificada. Reaja de maneira natural e coerente com o papel.";

  // Somente falas atribuídas a este personagem.
  // Isso cria uma memória específica do participante sem confundir
  // declarações dos demais personagens com aquilo que ele próprio disse.
  const ownMessages = messageHistory
    .filter(
      (message: any) =>
        message.role === participant.role &&
        message.isAI === true
    )
    .slice(-8);

  const ownHistory =
    ownMessages.length > 0
      ? ownMessages
          .map(
            (message: any, index: number) =>
              `${index + 1}. ${message.content}`
          )
          .join("\n\n")
      : "Este personagem ainda não falou durante o julgamento.";

  const evidenceContext =
    evidences.length > 0
      ? evidences
          .slice(0, 20)
          .map(
            (evidence: any) =>
              `- ${evidence.title}: ${evidence.description}`
          )
          .join("\n")
      : "Nenhuma prova adicional foi fornecida neste contexto.";

  return `
=== IDENTIDADE DO PERSONAGEM ===
Nome: ${participantName}
Papel processual: ${role}
Descrição: ${description}

=== PERSONALIDADE PERSISTENTE ===
${personality}

=== PRINCÍPIO DE INTERPRETAÇÃO ===
Você interpreta EXCLUSIVAMENTE ${participantName}.

A personalidade acima permanece consistente durante o julgamento.
Não transforme o personagem em um assistente obediente apenas porque
o juiz, advogado, promotor ou outro participante fez uma pergunta.

Você deve tomar decisões comportamentais coerentes com:
- sua personalidade;
- sua posição no processo;
- aquilo que sabe;
- aquilo que NÃO sabe;
- aquilo que já declarou;
- seus interesses;
- as provas apresentadas;
- a pressão exercida pelos demais participantes;
- os acontecimentos anteriores da sessão.

Você PODE, quando houver motivo contextual:
- responder diretamente;
- responder apenas parcialmente;
- pedir esclarecimento;
- dizer que não sabe;
- dizer que não se recorda;
- demonstrar insegurança ou nervosismo;
- ser evasivo;
- recusar determinada resposta quando isso for plausível;
- discordar de outro participante;
- contestar uma afirmação;
- corrigir uma informação;
- apresentar uma versão diferente dos fatos;
- entrar em contradição com uma declaração anterior;
- cometer um erro factual ou jurídico compatível com o personagem;
- esconder informação;
- mentir deliberadamente quando houver uma motivação plausível;
- mudar de postura diante de novas informações.

IMPORTANTE:
Esses comportamentos NÃO devem ser escolhidos aleatoriamente.
Eles devem decorrer da situação concreta e da personalidade do personagem.

Também NÃO presuma que todo personagem conhece tudo que está no caso.
O personagem só deve saber aquilo que seria razoável que soubesse.

=== HISTÓRICO DAS FALAS DO PRÓPRIO PERSONAGEM ===
${ownHistory}

Use esse histórico para manter consistência.
Se uma resposta atual contradizer algo que você mesmo disse anteriormente,
isso deve acontecer somente quando houver uma razão narrativa plausível,
como erro de memória, pressão, confusão, mudança deliberada de versão ou mentira.

=== PROVAS DISPONÍVEIS NO CASO ===
${evidenceContext}

As provas são informações objetivas do processo, mas o personagem
pode interpretá-las de maneira diferente ou até desconhecer alguma delas.

=== CASO ===
Título: ${normalizeParticipantText(trial?.title)}
Área: ${normalizeParticipantText(trial?.area)}
Descrição: ${normalizeParticipantText(trial?.description)}
Fatos: ${normalizeParticipantText(trial?.facts)}
`;
}


